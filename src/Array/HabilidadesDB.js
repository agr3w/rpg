/**
 * Retorna TODAS as habilidades da raça e TODA a árvore da classe (Níveis 1 a 20) para o Compêndio
 */
export function getCompendioProgressao(ficha) {
  if (!ficha) return [];

  const racaNorm = normalizeString(ficha.raca);
  const subracaNorm = normalizeString(ficha.subraca || ficha.DetalhesDaRaça?.SubRaca);
  const classeNorm = normalizeString(ficha.classe);
  const subclasseNorm = normalizeString(ficha.subclasse || ficha.subClasse);
  const nivelAtual = Number(ficha.nivel || ficha.level) || 1;

  // 1. Raciais e Sub-raciais
  const raciais = HABILIDADES_RACIAIS.filter((h) => {
    const v = normalizeString(h.vinculo);
    if (!v) return false;
    const matchRaca = racaNorm && (racaNorm.includes(v) || v.includes(racaNorm));
    const matchSubraca = subracaNorm && (subracaNorm.includes(v) || v.includes(subracaNorm));
    return matchRaca || matchSubraca;
  }).map((h) => ({
    ...h,
    categoria: h.categoria || "raca",
    origem: "raca",
    adquirida: true,
    desbloqueado: true,
    origemLabel: h.categoria === "subraca" ? `Sub-raça (${h.vinculo})` : `Raça (${h.vinculo})`,
    subOrigem: h.vinculo || "Raça",
  }));

  // 2. Classe Base
  const deClasseBase = HABILIDADES_CLASSES.filter((h) => {
    const v = normalizeString(h.vinculo);
    if (!v) return false;
    return (v === classeNorm || classeNorm.includes(v)) && h.categoria === "classe";
  }).map((h) => {
    const isAdquirida = Number(h.nivel || 1) <= nivelAtual;
    return {
      ...h,
      categoria: "classe",
      origem: "classe",
      adquirida: isAdquirida,
      desbloqueado: isAdquirida,
      origemLabel: `${h.vinculo} (Nível ${h.nivel})`,
      subOrigem: `${h.vinculo} (Nvl ${h.nivel})`,
    };
  });

  // 3. Subclasse (Se selecionada, puxa a árvore dela)
  let deSubclasse = [];
  if (subclasseNorm) {
    deSubclasse = HABILIDADES_CLASSES.filter((h) => {
      const v = normalizeString(h.vinculo);
      if (!v) return false;
      return (
        (v === subclasseNorm || subclasseNorm.includes(v) || v.includes(subclasseNorm)) &&
        h.categoria === "subclasse"
      );
    }).map((h) => {
      const isAdquirida = Number(h.nivel || 1) <= nivelAtual;
      return {
        ...h,
        categoria: "subclasse",
        origem: "classe",
        adquirida: isAdquirida,
        desbloqueado: isAdquirida,
        origemLabel: `Subclasse: ${h.vinculo} (Nível ${h.nivel})`,
        subOrigem: `${h.vinculo} (Nvl ${h.nivel})`,
      };
    });
  }

  // 4. Invocações Místicas (Exclusivas de Bruxo)
  let deInvocacoes = [];
  if (classeNorm === "bruxo") {
    deInvocacoes = INVOCOES_MISTICAS_BRUXO.map((h) => {
      const isDesbloqueada = Number(h.nivel || 1) <= nivelAtual;
      return {
        ...h,
        categoria: "invocacao",
        origem: "classe",
        adquirida: isDesbloqueada,
        desbloqueado: isDesbloqueada,
        origemLabel: `Invocação Mística (Nível ${h.nivel})`,
        subOrigem: `Invocação (Nvl ${h.nivel})`,
      };
    });
  }

  // 5. Metamágicas (Exclusivas de Feiticeiro)
  let deMetamagicas = [];
  if (classeNorm === "feiticeiro") {
    deMetamagicas = HABILIDADES_FEITICEIRO.filter((h) => h.categoria === "metamagica").map((h) => {
      const isDesbloqueada = nivelAtual >= 3;
      return {
        ...h,
        categoria: "metamagica",
        origem: "classe",
        adquirida: isDesbloqueada,
        desbloqueado: isDesbloqueada,
        origemLabel: `Metamágica (Nível ${h.nivel})`,
        subOrigem: `Metamágica (Nvl ${h.nivel})`,
      };
    });
  }

  // 6. Habilidades personalizadas / livres / talentos
  const livres = (ficha.habilidadesLivres || []).map((h) => ({
    ...h,
    categoria: "livre",
    origem: "talento",
    adquirida: true,
    desbloqueado: true,
    origemLabel: "Talento / Livre",
    subOrigem: h.subOrigem || h.vinculo || "Talento / Livre",
    nivel: Number(h.nivel || h.level || 1),
    tipoAcao: h.tipoAcao || "Passiva",
  }));

  return [...raciais, ...deClasseBase, ...deSubclasse, ...deInvocacoes, ...deMetamagicas, ...livres];
}

/**
 * Retorna apenas as habilidades ativas/desbloqueadas no nível atual do personagem
 */
export function getHabilidadesAtivas(ficha) {
  if (!ficha) return [];
  const full = getCompendioProgressao(ficha);
  return full.filter((h) => h.adquirida);
}

// Aliases para retrocompatibilidade
export const getHabilidadesPersonagem = (ficha, incluirFuturas = false) => {
  return incluirFuturas ? getCompendioProgressao(ficha) : getHabilidadesAtivas(ficha);
};
export const getCompendioCompleto = (ficha) => getCompendioProgressao(ficha);

/**
 * Calcula o valor numérico de usos máximos para rastreadores de combate
 */
export function calcularUsosMaximos(habilidade, ficha) {
  if (!habilidade) return null;
  if (typeof habilidade.usosMax === "number") return habilidade.usosMax;
  if (!habilidade.usosMax) return null;

  const nivel = Number(ficha?.nivel) || 1;
  const carMod = Math.floor(((ficha?.atributos?.carisma || 10) - 10) / 2);
  const sabMod = Math.floor(((ficha?.atributos?.sabedoria || 10) - 10) / 2);
  const conMod = Math.floor(((ficha?.atributos?.constituicao || 10) - 10) / 2);
  const intMod = Math.floor(((ficha?.atributos?.inteligencia || 10) - 10) / 2);

  switch (habilidade.usosMax) {
    case "MOD_CAR":
    case "INSPIRACAO_BARDO":
      return Math.max(1, carMod);
    case "MOD_SAB":
      return Math.max(1, sabMod);
    case "MOD_CON":
      return Math.max(1, conMod);
    case "MOD_INT":
      return Math.max(1, intMod);
    case "1 + MOD_CAR":
      return Math.max(1, 1 + carMod);
    case "NIVEL_PALADINO * 5":
    case "NIVEL * 5":
      return nivel * 5;
    case "PONTOS_CHI":
    case "PONTOS_FEITICARIA":
    case "NIVEL_FEITICEIRO":
      return nivel;
    case "TABELA_FURIA":
      if (nivel >= 20) return 999;
      if (nivel >= 17) return 6;
      if (nivel >= 12) return 5;
      if (nivel >= 6) return 4;
      if (nivel >= 3) return 3;
      return 2;
    case "CANALIZAR_DIVINDADE":
      if (nivel >= 18) return 3;
      if (nivel >= 6) return 2;
      return 1;
    case "TABELA_SURTO_ACAO":
      return nivel >= 17 ? 2 : 1;
    case "TABELA_INDOMAVEL":
      if (nivel >= 17) return 3;
      if (nivel >= 13) return 2;
      return 1;
    case "TABELA_FORMA_SELVAGEM":
      return nivel >= 20 ? 999 : 2;
    default:
      if (!isNaN(Number(habilidade.usosMax))) {
        return Number(habilidade.usosMax);
      }
      return null;
  }
}
